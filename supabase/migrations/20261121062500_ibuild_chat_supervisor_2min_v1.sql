-- 24/7 chat supervision: deterministic, 2-minute monitoring.
-- IMPORTANT: this SQL does not operate a browser, generate model output, or bypass ChatGPT limits.
-- Only authenticated desktop telemetry can authorize a prepared browser prompt.
create table if not exists public.ibuild_nexus_autopilot_keys(
 id smallint primary key default 1 check(id=1),
 token_sha256 text not null check(token_sha256 ~ '^[a-f0-9]{64}$'),
 enabled boolean not null default true,
 rotated_at timestamptz not null default now()
);
alter table public.ibuild_nexus_autopilot_keys enable row level security;
revoke all on public.ibuild_nexus_autopilot_keys from public,anon,authenticated;
grant select on public.ibuild_nexus_autopilot_keys to service_role;
